export function encontrarCidade(nome: string): CidadeBR | null {
  if (!nome) return null
  const normalizado = nome.toLowerCase().trim()
  return CIDADES_BR.find(c =>
    c.nome.toLowerCase() === normalizado ||
    c.nome.toLowerCase().includes(normalizado) ||
    normalizado.includes(c.nome.toLowerCase())
  ) ?? null
}
